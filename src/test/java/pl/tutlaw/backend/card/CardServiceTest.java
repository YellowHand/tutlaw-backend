package pl.tutlaw.backend.card;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.ArgumentCaptor;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import pl.tutlaw.backend.card.dto.BulkImportResult;
import pl.tutlaw.backend.card.dto.CardRequest;
import pl.tutlaw.backend.card.dto.CardResponse;
import pl.tutlaw.backend.chapter.ChapterRepository;
import pl.tutlaw.backend.common.exception.ConflictException;
import pl.tutlaw.backend.common.exception.ResourceNotFoundException;
import pl.tutlaw.backend.source.Source;
import pl.tutlaw.backend.source.SourceRepository;
import pl.tutlaw.backend.source.SourceType;
import pl.tutlaw.backend.tag.TagRepository;

import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyList;
import static org.mockito.Mockito.lenient;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

@ExtendWith(MockitoExtension.class)
class CardServiceTest {

    @Mock private CardRepository cardRepository;
    @Mock private ChapterRepository chapterRepository;
    @Mock private SourceRepository sourceRepository;
    @Mock private TagRepository tagRepository;

    private CardService service;
    private final List<Card> existing = new ArrayList<>();

    @BeforeEach
    void setUp() {
        service = new CardService(cardRepository, chapterRepository, sourceRepository, tagRepository);
        Source source = new Source();
        source.setId(7L);
        source.setName("Zestaw");
        source.setSourceType(SourceType.FLAT_POOL);
        lenient().when(sourceRepository.findById(7L)).thenReturn(Optional.of(source));
        lenient().when(cardRepository.findBySourceId(7L)).thenAnswer(inv -> new ArrayList<>(existing));
        lenient().when(cardRepository.save(any(Card.class))).thenAnswer(inv -> inv.getArgument(0));
    }

    private static CardRequest question(QuestionOrigin origin, Integer year) {
        return new CardRequest(null, 7L, CardType.DEFINITION, "Termin?", null, null, false, null,
                "7 dni", "14 dni", "30 dni", CorrectOption.A, null, null, null, null, origin, year);
    }

    private Card existingQuestion(QuestionOrigin origin, Integer year) {
        Card card = new Card();
        card.setFront("Termin?");
        card.setOptionA("7 dni");
        card.setOptionB("14 dni");
        card.setOptionC("30 dni");
        card.setCorrectOption(CorrectOption.A);
        card.setOrigin(origin);
        card.setExamYear(year);
        existing.add(card);
        return card;
    }

    @Test
    void create_storesOriginAndYearOfAnApplicationQuestion() {
        CardResponse response = service.create(question(QuestionOrigin.NOTARY, 2021));

        assertThat(response.origin()).isEqualTo(QuestionOrigin.NOTARY);
        assertThat(response.examYear()).isEqualTo(2021);
        assertThat(response.hidden()).isFalse();
        assertThat(response.autoGenerated()).isFalse();
    }

    @Test
    void create_withoutOrigin_makesAnAuthoredQuestionWithoutYear() {
        CardResponse response = service.create(question(null, null));

        assertThat(response.origin()).isEqualTo(QuestionOrigin.AUTHORED);
        assertThat(response.examYear()).isNull();
    }

    @Test
    void create_applicationQuestionWithoutYear_isRejected() {
        assertThatThrownBy(() -> service.create(question(QuestionOrigin.JUDGE_PROSECUTOR, null)))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("rok");
        verify(cardRepository, never()).save(any());
    }

    @Test
    void create_authoredQuestionWithYear_isRejected() {
        assertThatThrownBy(() -> service.create(question(QuestionOrigin.AUTHORED, 2021)))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("autorskie");
    }

    @Test
    void create_theSameQuestionFromAnotherYear_isAllowed() {
        existingQuestion(QuestionOrigin.NOTARY, 2019);

        CardResponse response = service.create(question(QuestionOrigin.NOTARY, 2022));

        assertThat(response.examYear()).isEqualTo(2022);
    }

    @Test
    void create_theSameQuestionFromAnotherApplicationOrAuthored_isAllowed() {
        existingQuestion(QuestionOrigin.NOTARY, 2019);

        assertThat(service.create(question(QuestionOrigin.BAILIFF, 2019)).origin()).isEqualTo(QuestionOrigin.BAILIFF);
        assertThat(service.create(question(null, null)).origin()).isEqualTo(QuestionOrigin.AUTHORED);
    }

    @Test
    void create_theSameQuestionFromTheSameApplicationAndYear_isAConflict() {
        existingQuestion(QuestionOrigin.NOTARY, 2019);

        assertThatThrownBy(() -> service.create(question(QuestionOrigin.NOTARY, 2019)))
                .isInstanceOf(ConflictException.class);
    }

    @Test
    void create_aHandWrittenFlashcardIdenticalToAnAutoGeneratedOne_isNotAConflict() {
        Card auto = new Card();
        auto.setFront("Pojęcie");
        auto.setBack("Definicja");
        auto.setAutoGenerated(true);
        existing.add(auto);
        CardRequest flashcard = new CardRequest(null, 7L, CardType.DEFINITION, "Pojęcie", "Definicja", null, false,
                null, null, null, null, null, null, null, null, null, null, null);

        CardResponse response = service.create(flashcard);

        assertThat(response.front()).isEqualTo("Pojęcie");
    }

    @Test
    void bulkCreate_keepsTheSameQuestionFromDifferentYears_andSkipsOnlyTrueDuplicates() {
        BulkImportResult result = service.bulkCreate(List.of(
                question(QuestionOrigin.NOTARY, 2019),
                question(QuestionOrigin.NOTARY, 2022),
                question(QuestionOrigin.NOTARY, 2019)));

        assertThat(result.created()).isEqualTo(2);
        assertThat(result.duplicates()).isEqualTo(1);
        assertThat(result.errors()).isEmpty();
    }

    @Test
    void bulkCreate_reportsAMissingYearAsARowError() {
        BulkImportResult result = service.bulkCreate(List.of(question(QuestionOrigin.BAILIFF, null)));

        assertThat(result.created()).isZero();
        assertThat(result.errors()).hasSize(1);
        assertThat(result.errors().get(0)).contains("Wiersz 1").contains("rok");
    }

    @Test
    void setHidden_hidesAndRestoresTheCard() {
        Card card = new Card();
        card.setId(5L);
        Source source = new Source();
        source.setId(7L);
        card.setSource(source);
        when(cardRepository.findById(5L)).thenReturn(Optional.of(card));

        assertThat(service.setHidden(5L, true).hidden()).isTrue();
        assertThat(card.isHidden()).isTrue();
        assertThat(service.setHidden(5L, false).hidden()).isFalse();
        assertThat(card.isHidden()).isFalse();
    }

    @Test
    void setHidden_unknownCard_isNotFound() {
        when(cardRepository.findById(99L)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> service.setHidden(99L, true)).isInstanceOf(ResourceNotFoundException.class);
    }
}
