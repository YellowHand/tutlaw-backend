package pl.tutlaw.backend.card;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.BatchSize;
import pl.tutlaw.backend.chapter.Chapter;
import pl.tutlaw.backend.source.Source;
import pl.tutlaw.backend.tag.Tag;

import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.HashSet;
import java.util.Set;

@Entity
@Table(name = "cards")
@Getter
@Setter
@NoArgsConstructor
public class Card {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "chapter_id")
    private Chapter chapter;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "source_id", nullable = false)
    private Source source;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private CardType type;

    @Column(columnDefinition = "TEXT", nullable = false)
    private String front;

    /** Odpowiedź na odwrocie fiszki. Wymagana tylko dla fiszki; pytanie testowe ma ją w correctOption (tu zwykle null). */
    @Column(columnDefinition = "TEXT")
    private String back;

    @Column(name = "page_number")
    private Integer pageNumber;

    @Column(name = "is_verbatim_quote", nullable = false)
    private boolean verbatimQuote = false;

    @Column(name = "option_a", columnDefinition = "TEXT")
    private String optionA;

    @Column(name = "option_b", columnDefinition = "TEXT")
    private String optionB;

    @Column(name = "option_c", columnDefinition = "TEXT")
    private String optionC;

    @Enumerated(EnumType.STRING)
    @Column(name = "correct_option")
    private CorrectOption correctOption;

    @Column(columnDefinition = "TEXT")
    private String explanation;

    /**
     * Tylko fiszka (karta bez opcji): numer pytania testowego, z którym jest powiązana. Taka fiszka pokazuje się
     * w Fiszkach dopiero po błędzie w tym pytaniu (zob. {@link CardScopes#isUnlocked}). Zwykły numer zamiast
     * relacji, bo służy do filtrowania w pamięci i nie ma po co ładować drugiej karty.
     */
    @Column(name = "linked_test_card_id")
    private Long linkedTestCardId;

    /** Podstawa prawna, np. "art. 415 k.c." Opcjonalna; pokazywana uczącemu się przy odpowiedzi. */
    @Column(name = "legal_basis", columnDefinition = "TEXT")
    private String legalBasis;

    /** Na jaki dzień sprawdzono stan prawny pytania. Opcjonalne. */
    @Column(name = "valid_as_of")
    private LocalDate validAsOf;

    /** Etykiety wczytywane partiami (po 100 kart naraz), żeby lista kart nie robiła osobnego zapytania na każdą kartę. */
    @BatchSize(size = 100)
    @ManyToMany
    @JoinTable(
            name = "card_tags",
            joinColumns = @JoinColumn(name = "card_id"),
            inverseJoinColumns = @JoinColumn(name = "tag_id")
    )
    private Set<Tag> tags = new HashSet<>();

    /**
     * Skąd pochodzi karta: pytanie autorskie albo egzamin wstępny na konkretną aplikację. Dla fiszki z pytania
     * kopiowane z pytania (utrzymuje to wyzwalacz w bazie).
     */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private QuestionOrigin origin = QuestionOrigin.AUTHORED;

    /** Rok egzaminu, z którego pochodzi pytanie. Wymagany dla pytań z aplikacji, pusty dla autorskich. */
    @Column(name = "exam_year")
    private Integer examYear;

    /**
     * Ukryta karta nie pojawia się nikomu (testy, fiszki, liczniki, egzamin), a historia odpowiedzi zostaje.
     * Ukrycie pytania ukrywa też jego automatyczną fiszkę (robi to wyzwalacz w bazie).
     */
    @Column(nullable = false)
    private boolean hidden = false;

    /**
     * Fiszka utworzona automatycznie z pytania testowego (jej przód, tył i pochodzenie utrzymuje wyzwalacz w bazie
     * i nie należy ich zmieniać ręcznie). Fiszka napisana ręcznie ma false.
     */
    @Column(name = "auto_generated", nullable = false)
    private boolean autoGenerated = false;

    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt = LocalDateTime.now();
}