package pl.tutlaw.backend.card;

import pl.tutlaw.backend.card.dto.CardResponse;
import pl.tutlaw.backend.tag.Tag;

public class CardMapper {
    public static CardResponse toResponse(Card card) {
        return new CardResponse(
                card.getId(),
                card.getChapter() != null ? card.getChapter().getId() : null,
                card.getSource().getId(),
                card.getType(), card.getFront(), card.getBack(),
                card.getPageNumber(), card.isVerbatimQuote(),
                card.getTags().stream().map(Tag::getName).toList(),
                card.getOptionA(), card.getOptionB(), card.getOptionC(),
                card.getCorrectOption(), card.getExplanation(),
                card.getLegalBasis(), card.getValidAsOf(), card.getLinkedTestCardId(),
                card.getOrigin(), card.getExamYear(), card.isHidden(), card.isAutoGenerated()
        );
    }
}